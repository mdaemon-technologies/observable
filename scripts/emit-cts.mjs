// Writes dist/observable.d.cts, the types for `require("@mdaemon/observable")`, from
// the declarations tsc has just emitted. `npm run build` runs it after tsc.
//
// The package is "type": "module", so TypeScript reads every .d.ts in it as an ES
// module. CommonJS consumers under node16/nodenext need a .d.cts that uses
// `export =`, matching `module.exports = observe` in observable.cjs. tsc cannot emit
// that from the ESM source, so this script writes it: the value is typed from the
// generated observable.d.ts, and a namespace merged into it re-exports every type
// that file exports, so the list can never drift from the source.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dist = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "dist");
const source = fs.readFileSync(path.join(dist, "observable.d.ts"), "utf8");

const match = source.match(/export type \{([^}]*)\}/);
const types = match ? match[1].split(",").map((name) => name.trim()).filter(Boolean) : [];
if (!types.includes("ObserveFunction")) {
  console.error("emit-cts: dist/observable.d.ts has no `export type { ... }` list that includes ObserveFunction");
  process.exit(1);
}

const output = `// Generated by scripts/emit-cts.mjs during \`npm run build\`. Do not edit.
//
// Types for \`require("@mdaemon/observable")\`. The package is "type": "module", so
// TypeScript reads every .d.ts in it as an ES module; CommonJS consumers under
// node16/nodenext need this .d.cts, which uses \`export =\` like observable.cjs. The
// namespace re-exports every type in observable.d.ts, so
// \`import type { Unsubscribe } from "@mdaemon/observable"\` works from CommonJS too.
import type * as types from "./observable.js" with { "resolution-mode": "import" };

declare const observe: types.ObserveFunction;

declare namespace observe {
${types.map((name) => `  type ${name} = types.${name};`).join("\n")}
}

export = observe;
`;

fs.writeFileSync(path.join(dist, "observable.d.cts"), output);
console.log(`emit-cts: wrote dist/observable.d.cts with ${types.length} types`);
